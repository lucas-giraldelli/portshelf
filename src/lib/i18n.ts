const dictionaries: Record<Lang, Record<Key, string>> = { en, "pt-BR": ptBR };

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const text = dictionaries[lang]?.[key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

export function defaultLang(): Lang {
  const system = typeof navigator !== "undefined" ? navigator.language : "en";
  return system.toLowerCase().startsWith("pt") ? "pt-BR" : "en";
}
